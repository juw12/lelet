export function makeT(lang) {
  const table = STRINGS[lang] || STRINGS.id;
  return (key, vars = {}) => {
    const text = table[key] ?? STRINGS.id[key] ?? key;
    return text
      .replace(/\{(\w+)\}/g, (match, name) => (name in vars ? String(vars[name]) : match))
      .replace(/\[(\w+):([^|\]]*)\|([^\]]*)\]/g, (match, name, one, many) => (Number(vars[name]) === 1 ? one : many));
  };
}
